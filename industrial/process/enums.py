"""Typed vocabulary for the isolated manufacturing-cell simulator."""
from enum import Enum


class ProcessAsset(str, Enum):
    PRODUCTION_CONTROLLER = "PRODUCTION_CONTROLLER"
    MIXER = "MIXER"
    PUMP = "PUMP"
    CONVEYOR = "CONVEYOR"


class OperatingMode(str, Enum):
    NORMAL = "NORMAL"
    HIGH_OUTPUT = "HIGH_OUTPUT"
    MAINTENANCE = "MAINTENANCE"
    SHUTDOWN = "SHUTDOWN"


class MachineState(str, Enum):
    STOPPED = "STOPPED"
    STARTING = "STARTING"
    RUNNING = "RUNNING"
    STOPPING = "STOPPING"
    FAULT = "FAULT"
    EMERGENCY_STOP = "EMERGENCY_STOP"


class ProcessOperation(str, Enum):
    SET_MIXER_SPEED_RPM = "SET_MIXER_SPEED_RPM"
    SET_PUMP_FLOW_RATE_LPM = "SET_PUMP_FLOW_RATE_LPM"
    SET_CONVEYOR_SPEED_MPS = "SET_CONVEYOR_SPEED_MPS"
    SET_PRODUCTION_RATE_UNITS_PER_HOUR = "SET_PRODUCTION_RATE_UNITS_PER_HOUR"
    CHANGE_OPERATING_MODE = "CHANGE_OPERATING_MODE"
    START_ASSET = "START_ASSET"
    STOP_ASSET = "STOP_ASSET"
    REQUEST_SHUTDOWN = "REQUEST_SHUTDOWN"
    EMERGENCY_STOP = "EMERGENCY_STOP"
    RESET_EMERGENCY = "RESET_EMERGENCY"


class InterlockStatus(str, Enum):
    ALLOWED = "ALLOWED"
    REJECTED_OUT_OF_RANGE = "REJECTED_OUT_OF_RANGE"
    REJECTED_INVALID_TRANSITION = "REJECTED_INVALID_TRANSITION"
    REJECTED_EMERGENCY_STATE = "REJECTED_EMERGENCY_STATE"
    REJECTED_MAINTENANCE_RESTRICTION = "REJECTED_MAINTENANCE_RESTRICTION"
    REJECTED_STATE_VERSION_MISMATCH = "REJECTED_STATE_VERSION_MISMATCH"
    REJECTED_INVALID_TARGET = "REJECTED_INVALID_TARGET"
    REJECTED_INVALID_OPERATION = "REJECTED_INVALID_OPERATION"
